def hist_map(y, m, d, h, title, sub, slug, cap, bounds, pts):
    ec = E.eclipse_near(E.jd_from_date(y, m, d, h))
    lon0, lon1, lat0, lat1 = bounds
    fig = plt.figure(figsize=(9.0, 6.4), facecolor=PAPER)
    ax = fig.add_axes([0.04, 0.10, 0.86, 0.68])
    MK.base(ax, lon0, lon1, lat0, lat1, highlight=(), admin1=None)
    MK.field(ax, ec.B, lon0, lon1, lat0, lat1, n=380)
    MK.path(ax, ec.B)
    MK.cities(ax, ec.B, pts, lon0, lon1, lat0, lat1, size=8.5)
    header(fig, title, sub)
    kind = {"total": "كلي", "annular": "حلقي", "hybrid": "هجين", "partial": "جزئي"}[ec.kind]
    note = f"{date_ar(*ec.date)} | النوع: {kind} | الذروة {I.fmt_time(ec.hour_ut, seconds=False)} بالتوقيت العالمي"
    if ec.backend == "erfa":
        note += f" | ΔT ≈ {A(f'{ec.delta_t:,.0f}')} ث"
    fig.text(0.965, 0.80, note, ha="right", fontsize=8.8, color=INK2)
    unc = ("المسار القديم تقريبي جدًا: عدم اليقين في ΔT قد يزيحه مئات الكيلومترات شرقًا أو غربًا."
           if y < 1000 else "")
    footer(fig, SRC + (" بنظرية ERFA ومعادلات ΔT لإسبيناك ومييس. " if ec.backend == "erfa" else " من تقويم JPL DE421. ") + unc)
    save(fig, CH, slug, cap, "map")


