def city_tables():
    rows = list(csv.DictReader(open(os.path.join(ROOT, "results", "local_circumstances_egypt.csv"), encoding="utf-8")))
    import sys
    sys.path.insert(0, ROOT)
    from eclipse2027 import i18n as I
    I.set_lang("ar")
    out = []
    for r in rows:
        tot = r["eclipse_type"] == "total"
        out.append([I.place(r["city"]), I.governorate(r["governorate"]), A(r["C1_local"]),
                    A(r["C2_local"]) if tot else "—", A(r["max_local"]), A(r["C3_local"]) if tot else "—",
                    A(r["C4_local"]), I.fmt_dur(float(r["totality_s"])) if tot else "—",
                    A(f"{float(r['obscuration_pct']):.1f}%"), A(r["sun_altitude_deg"]) + "°"])
    allr = list(csv.DictReader(open(os.path.join(ROOT, "results", "local_circumstances_all_cities.csv"), encoding="utf-8")))
    other = []
    cmap = {"Spain": "إسبانيا", "Gibraltar": "جبل طارق", "Morocco": "المغرب", "Algeria": "الجزائر", "Tunisia": "تونس",
            "Libya": "ليبيا", "Sudan (north-east)": "السودان", "Saudi Arabia": "السعودية", "Yemen": "اليمن",
            "Somalia (Puntland & Somaliland)": "الصومال"}
    for r in allr:
        if r["country"] == "Egypt":
            continue
        tot = r["eclipse_type"] == "total"
        off = int(r["utc_offset"])
        other.append([cmap.get(r["country"], r["country"]), I.place(r["city"]), A(r["max_local"]),
                      "ت.ع" + ("+" if off >= 0 else "−") + A(abs(off)),
                      I.fmt_dur(float(r["totality_s"])) if tot else "—", A(f"{float(r['obscuration_pct']):.1f}%")])
    return out, other


def build():
    cat = json.load(open(os.path.join(HERE, "catalogue.json"), encoding="utf-8"))
    egypt, other = city_tables()
    spec = dict(title=TITLE, subtitle=SUBTITLE, front=FRONT, edition=EDITION, notes=NOTES, method=METHOD, chapters=[], glossary=GLOSSARY, sources=SOURCES,
                egypt_table=egypt, other_table=other)
    for ch in range(1, 8):
        label, name, intro = CHAPTERS[ch]
        items = []
        for c in [c for c in cat if c["chapter"] == ch]:
            if c["number"] in SECTIONS:
                h, paras = SECTIONS[c["number"]]
                items.append(dict(type="h2", text=h))
                items += [dict(type="p", text=p) for p in paras]
            items.append(dict(type="figure", file=c["file"], number=c["number_ar"], caption=c["caption"]))
        spec["chapters"].append(dict(label=label, name=name, intro=intro, items=items))
    os.makedirs(os.path.join(HERE, "word"), exist_ok=True)
    json.dump(spec, open(os.path.join(HERE, "word", "manuscript.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("figures:", sum(1 for ch in spec["chapters"] for i in ch["items"] if i["type"] == "figure"))


if __name__ == "__main__":
    build()
